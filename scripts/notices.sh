#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES.md from the Go modules compiled into
# paygate for macOS, Linux and Windows, including their full license texts.
#
#   ./scripts/notices.sh      (or: make notices)

set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# "module@version<TAB>darwin, linux, windows" for every compiled module
# (plain bash 3 compatible, as shipped with macOS).
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
for os in darwin linux windows; do
  GOOS=$os go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}@{{.Version}}{{end}}{{end}}' ./cmd/paygate |
    sort -u | sed "/^$/d; s/$/ $os/" >> "$tmp"
done
modules="$(awk '{ p[$1] = p[$1] (p[$1] ? ", " : "") $2 } END { for (m in p) print m "\t" p[m] }' "$tmp" | sort)"

license_file() {
  ls "$1" | grep -iE '^(licen[cs]e|copying)(\.md|\.txt)?$' | head -1 || true
}

detect() {
  local text="$1"
  case "$text" in
    *"Apache License"*) echo "Apache-2.0" ;;
    *"MIT License"*|*"Permission is hereby granted, free of charge"*) echo "MIT" ;;
    *"Redistribution and use in source and binary forms"*)
      if grep -q "Neither the name" <<<"$text"; then echo "BSD-3-Clause"; else echo "BSD-2-Clause"; fi ;;
    *) echo "see below" ;;
  esac
}

out="THIRD_PARTY_NOTICES.md"
{
  echo "# Third-party notices"
  echo
  echo "paygate is licensed under the Apache License 2.0 (see LICENSE and NOTICE)."
  echo "Its binaries include the following open-source Go modules. Their license"
  echo "texts follow below. This file is generated by \`scripts/notices.sh\`."
  echo
  echo "| Module | Version | License | Platforms |"
  echo "| --- | --- | --- | --- |"
  while IFS=$'\t' read -r m plats; do
    mod="${m%@*}"; ver="${m##*@}"
    dir=$(go list -m -f '{{.Dir}}' "$mod")
    file=$(license_file "$dir")
    if [ -n "$file" ]; then lic=$(detect "$(head -c 4000 "$dir/$file")"); else lic="MIT (stated in its README)"; fi
    echo "| $mod | $ver | $lic | $plats |"
  done <<<"$modules"
  echo
  echo "## License texts"
  while IFS=$'\t' read -r m _; do
    mod="${m%@*}"; ver="${m##*@}"
    dir=$(go list -m -f '{{.Dir}}' "$mod")
    file=$(license_file "$dir")
    echo
    echo "### $mod $ver"
    echo
    echo '```text'
    if [ -n "$file" ]; then
      sed -e 's/[[:space:]]*$//' "$dir/$file"
    else
      echo "No license file is shipped with this module; its README states: MIT."
    fi
    echo '```'
  done <<<"$modules"
} > "$out"
echo "Wrote $out ($(wc -l < "$out" | tr -d ' ') lines)"
